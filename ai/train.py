#!/usr/bin/env python3
"""
Train the congestion predictor from the controller's link statistics.

    features: last 5 utilisation readings of a link + its active flow count
    target:   the link's utilisation 10 seconds (5 samples) later

Trains Linear Regression and Random Forest on a time-ordered split (first 80 %
of every link's history for training, last 20 % for testing), compares them with
the moving-average fallback using MAE / RMSE, saves the better model with joblib
and writes the results to ai/models/metrics.json and docs/ai_training_results.md.

Usage:  python ai/train.py [--csv ai/data/link_stats.csv]
"""
import argparse
import json
import os
import sys
import time

import joblib
import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestRegressor
from sklearn.linear_model import LinearRegression
from sklearn.metrics import mean_absolute_error, mean_squared_error

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import config  # noqa: E402
from ai.features import FEATURE_NAMES, HORIZON_STEPS, WINDOW, build_samples  # noqa: E402
from ai.predictor import fallback_prediction  # noqa: E402

DOC_PATH = os.path.join(config.BASE_DIR, "docs", "ai_training_results.md")
METRICS_PATH = os.path.join(os.path.dirname(config.MODEL_PATH), "metrics.json")


def contiguous_segments(df, interval):
    """Split one link's rows wherever there is a gap (controller restart etc.)."""
    gap = df["ts"].diff().fillna(interval) > interval * 2.5
    return [seg for _, seg in df.groupby(gap.cumsum())]


def make_dataset(csv_path, train_frac=0.8):
    df = pd.read_csv(csv_path)
    required = {"ts", "link", "util", "flows"}
    if not required.issubset(df.columns):
        raise SystemExit("CSV %s must contain columns %s" % (csv_path, sorted(required)))
    df = df.sort_values(["link", "ts"])
    X_tr, y_tr, X_te, y_te = [], [], [], []
    for _link, link_df in df.groupby("link"):
        cut_ts = link_df["ts"].quantile(train_frac)
        for seg in contiguous_segments(link_df, config.STATS_INTERVAL):
            X, y = build_samples(seg["util"].tolist(), seg["flows"].tolist())
            target_ts = seg["ts"].tolist()[WINDOW - 1 + HORIZON_STEPS:]
            for row, label, ts in zip(X, y, target_ts):
                if ts <= cut_ts:
                    X_tr.append(row)
                    y_tr.append(label)
                else:
                    X_te.append(row)
                    y_te.append(label)
    return (np.array(X_tr), np.array(y_tr), np.array(X_te), np.array(y_te), len(df),
            df["link"].nunique())


def evaluate(y_true, y_pred):
    return {"mae": float(mean_absolute_error(y_true, y_pred)),
            "rmse": float(np.sqrt(mean_squared_error(y_true, y_pred)))}


def write_report(results, best, n_rows, n_links, n_train, n_test, csv_path):
    lines = [
        "# AI congestion predictor - training results",
        "",
        "Generated by `ai/train.py` on %s from `%s`." % (time.strftime("%Y-%m-%d %H:%M"),
                                                         os.path.relpath(csv_path, config.BASE_DIR)),
        "",
        "* Rows in CSV: %d (%d links)" % (n_rows, n_links),
        "* Samples: %d train / %d test (time-ordered 80/20 split per link)" % (n_train, n_test),
        "* Features: %s" % ", ".join(FEATURE_NAMES),
        "* Target: utilisation %d s ahead (%d samples at %.0f s)" % (
            config.PREDICTION_HORIZON_SECONDS, HORIZON_STEPS, config.STATS_INTERVAL),
        "",
        "| Model | MAE (% util) | RMSE (% util) |",
        "|---|---|---|",
    ]
    for name, m in results.items():
        lines.append("| %s%s | %.3f | %.3f |" % (name, " (saved)" if name == best else "",
                                                 m["mae"], m["rmse"]))
    lines += ["", "Lower is better. The saved model is loaded by the controller at start-up;",
              "without it the controller uses the moving-average fallback.", ""]
    os.makedirs(os.path.dirname(DOC_PATH), exist_ok=True)
    with open(DOC_PATH, "w") as fh:
        fh.write("\n".join(lines))


def main():
    parser = argparse.ArgumentParser(description="Train the link congestion predictor")
    parser.add_argument("--csv", default=config.STATS_CSV)
    parser.add_argument("--model-out", default=config.MODEL_PATH)
    parser.add_argument("--no-report", action="store_true", help="do not write docs/metrics files")
    args = parser.parse_args()

    if not os.path.exists(args.csv):
        raise SystemExit("No training data at %s. Run the network and ai/collect_data.py first."
                         % args.csv)
    X_tr, y_tr, X_te, y_te, n_rows, n_links = make_dataset(args.csv)
    if len(X_tr) < 50 or len(X_te) < 10:
        raise SystemExit("Not enough samples (train=%d, test=%d). Collect more data."
                         % (len(X_tr), len(X_te)))
    print("Dataset: %d rows, %d links -> %d train / %d test samples"
          % (n_rows, n_links, len(X_tr), len(X_te)))

    models = {
        "linear_regression": LinearRegression(),
        "random_forest": RandomForestRegressor(n_estimators=100, max_depth=12, min_samples_leaf=3,
                                               n_jobs=-1, random_state=42),
    }
    results = {}
    baseline = [fallback_prediction(row[:WINDOW]) for row in X_te]
    results["moving_average_fallback"] = evaluate(y_te, baseline)
    for name, model in models.items():
        start = time.time()
        model.fit(X_tr, y_tr)
        results[name] = evaluate(y_te, np.clip(model.predict(X_te), 0, 100))
        results[name]["train_seconds"] = round(time.time() - start, 2)

    print("\n%-26s %10s %10s" % ("model", "MAE", "RMSE"))
    for name, m in results.items():
        print("%-26s %10.3f %10.3f" % (name, m["mae"], m["rmse"]))

    best = min(models, key=lambda n: results[n]["mae"])
    os.makedirs(os.path.dirname(args.model_out), exist_ok=True)
    joblib.dump({"model": models[best], "name": best, "features": FEATURE_NAMES,
                 "window": WINDOW, "horizon_steps": HORIZON_STEPS,
                 "metrics": results, "trained_at": time.time()}, args.model_out)
    print("\nSaved %s to %s (restart the controller to load it)" % (best, args.model_out))

    if not args.no_report:
        with open(METRICS_PATH, "w") as fh:
            json.dump({"best": best, "results": results, "train_samples": len(X_tr),
                       "test_samples": len(X_te)}, fh, indent=2)
        write_report(results, best, n_rows, n_links, len(X_tr), len(X_te), args.csv)
        print("Report written to %s" % DOC_PATH)


if __name__ == "__main__":
    main()
